import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { serviceLocationPages } from '../src/data/serviceLocationPages.ts';
import { services } from '../src/data/services.ts';

const root = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8');
const baseline = JSON.parse(read('docs/ms-a9-baseline-2026-11-13.json'));
const featured = read('src/pages/index.astro').match(/const featuredServiceSlugs = \[([\s\S]*?)\] as const;/)?.[1];
const winter = [...(featured ?? '').matchAll(/"([^"]+)"/g)].map((m) => m[1]);
const driveways = services.filter((s) => /driveway/.test(s.slug)).map((s) => s.slug);
export const priorityServices = [...new Set([...winter, ...driveways])];
if (winter.length !== 4 || driveways.length !== 2 || priorityServices.length !== 6 ||
    priorityServices.some((slug) => !services.some((s) => s.slug === slug))) {
  throw new Error('Expected exactly four homepage features plus two driveway services');
}
const normalize = (url) => new URL(url, 'https://maestrosservices.com').pathname.replace(/\/+$/, '');
const rows = new Map();
for (const row of baseline.pages) {
  const key = normalize(row.page);
  if (rows.has(key)) throw new Error(`Duplicate baseline path: ${key}`);
  rows.set(key, row);
}
export const decisions = serviceLocationPages.map(({ href, service }) => {
  const row = rows.get(href);
  if (!row) throw new Error(`Missing baseline combo: ${href}`);
  return { href, a: priorityServices.includes(service.slug),
    b: typeof row.position === 'number' && row.position >= 8 && row.position <= 25,
    c: row.clicks > 0 };
});
export const keepPaths = decisions.filter((d) => d.a || d.b || d.c).map((d) => d.href).sort();
export const generatedSource = `// Generated by npm run ms-a9:generate; do not edit manually.
// Baseline: docs/ms-a9-baseline-2026-11-13.json; window ${baseline.meta.window.startDate} through ${baseline.meta.window.endDate}.
// Keep current combos if (a) homepage's four featured services + two driveway services,
// OR (b) baseline position 8..25 inclusive, OR (c) baseline clicks > 0.
export const msA9KeepPaths: readonly string[] = ${JSON.stringify(keepPaths, null, 2)};
`;
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('src/data/msA9KeepList.ts', root), generatedSource);
  const overlaps = {};
  for (const d of decisions) {
    const key = ['a', 'b', 'c'].filter((k) => d[k]).join('') || 'none';
    overlaps[key] = (overlaps[key] ?? 0) + 1;
  }
  console.log(JSON.stringify({ priorityServices, kept: keepPaths.length, noindexed: decisions.length - keepPaths.length, overlaps }, null, 2));
}
